def display_summary(students):
    for name, marks in students.items():
        avg = calculate_average(marks)
        passed = has_passed(avg)

        print("Student:", name)
        print("Marks:", marks)
        print("Average:", round(avg, 2))

        if passed:
            print("Status: PASSED")
        else:
            print("Status: FAILED")

        print("-----------")

