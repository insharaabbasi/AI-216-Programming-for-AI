class Dataset:
    def __init__(self, values):
        self.values = values

    def count(self):
        return len(self.values)

    def average(self):
        if len(self.values) == 0:
            return 0
        return sum(self.values) / len(self.values)

    def minimum(self):
        if len(self.values) == 0:
            return None
        return min(self.values)

    def maximum(self):
        if len(self.values) == 0:
            return None
        return max(self.values)

